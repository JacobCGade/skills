#!/usr/bin/env python3
"""Helpers for tracker-local tickets. Standard library only.

Usage:
  tickets.py index <dir>             Regenerate <dir>/index.md from the ticket files.
  tickets.py export-jira-csv <dir>   Write a Jira CSV import file to stdout for tickets
                                     without a jira-key. The column mapping goes to stderr.
"""
import csv
import re
import sys
from pathlib import Path

FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n?(.*)\Z", re.S)
LIST_KEYS = ("blocks", "blocked-by", "relates")


def parse_value(raw):
    raw = raw.strip()
    if raw.startswith("[") and raw.endswith("]"):
        return [item.strip() for item in raw[1:-1].split(",") if item.strip()]
    return raw


def read_ticket(path):
    match = FRONTMATTER.match(path.read_text(encoding="utf-8"))
    if not match:
        raise ValueError(f"{path}: missing frontmatter")
    meta = {}
    for line in match.group(1).splitlines():
        if ":" in line:
            key, value = line.split(":", 1)
            meta[key.strip()] = parse_value(value)
    for key in LIST_KEYS:
        meta.setdefault(key, [])
    body = match.group(2).split("\n## Comments", 1)[0].strip()
    return meta, body


def number(ref):
    digits = re.search(r"(\d+)$", ref or "")
    return int(digits.group(1)) if digits else 0


def load(directory):
    tickets = []
    for path in sorted(Path(directory).glob("*.md"), key=lambda p: number(p.stem)):
        if path.name == "index.md":
            continue
        meta, body = read_ticket(path)
        tickets.append((meta, body))
    return tickets


def write_index(directory):
    rows = ["| Ref | Type | Title | State | Parent | Blocked by |", "|---|---|---|---|---|---|"]
    for meta, _ in load(directory):
        rows.append("| {ref} | {type} | {title} | {state} | {parent} | {blocked} |".format(
            ref=meta.get("ref", ""), type=meta.get("type", ""), title=meta.get("title", ""),
            state=meta.get("state", ""), parent=meta.get("parent", ""),
            blocked=", ".join(meta["blocked-by"])))
    content = "# Tickets\n\nGenerated by tickets.py. Do not edit.\n\n" + "\n".join(rows) + "\n"
    (Path(directory) / "index.md").write_text(content, encoding="utf-8")
    print(f"index.md: {len(rows) - 2} tickets", file=sys.stderr)


def export_jira_csv(directory):
    tickets = [(m, b) for m, b in load(directory) if not m.get("jira-key")]
    imported = {m["ref"]: m["jira-key"] for m, _ in load(directory) if m.get("jira-key")}
    width = {key: max([len(m[key]) for m, _ in tickets] + [0]) for key in ("blocks", "relates")}
    header = ["Issue Id", "Parent Id", "Issue Type", "Summary", "Description", "Status"]
    header += ["Blocks"] * width["blocks"] + ["Relates"] * width["relates"]
    writer = csv.writer(sys.stdout)
    writer.writerow(header)
    for meta, body in tickets:
        parent = meta.get("parent", "")
        if parent in imported:
            print(f"warning: {meta['ref']} has parent {parent}, already imported as "
                  f"{imported[parent]}. Set the parent in Jira after import.", file=sys.stderr)
            parent = ""
        row = [number(meta["ref"]), number(parent) if parent else "", meta.get("type", ""),
               meta.get("title", ""), body, meta.get("state", "")]
        for key in ("blocks", "relates"):
            values = [str(number(ref)) for ref in meta[key]]
            row += values + [""] * (width[key] - len(values))
        writer.writerow(row)
    print("Jira CSV import mapping: Issue Id -> Issue Id, Parent Id -> Parent Id, "
          "Issue Type, Summary, Description, Status -> same names, "
          "Blocks -> Link 'Blocks', Relates -> Link 'Relates'. "
          f"{len(tickets)} tickets exported.", file=sys.stderr)


def main(argv):
    if len(argv) != 3 or argv[1] not in ("index", "export-jira-csv"):
        print(__doc__, file=sys.stderr)
        return 2
    {"index": write_index, "export-jira-csv": export_jira_csv}[argv[1]](argv[2])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
